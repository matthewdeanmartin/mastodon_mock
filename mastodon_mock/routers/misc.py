"""Static-shape stubs for obscure/rarely-used upstream endpoints.

None of these have a Mastodon.py caller; they exist only so the mock's contract
matches upstream's path/method surface. No persistence, no real behavior —
fixed-shape responses are sufficient (see spec/openapi_support.md Phase 3/4).
"""

from __future__ import annotations

from typing import Any

from fastapi import APIRouter, HTTPException

from mastodon_mock.deps import Config, RequiredAccount

router = APIRouter(tags=["misc"])


# --- oEmbed --------------------------------------------------------------


@router.get("/api/oembed")
def oembed(url: str, config: Config) -> dict[str, Any]:
    """Minimal OEmbed response for a status URL.

    ``author_url``/``provider_url`` must be valid URIs and ``width`` is required
    (OEmbedResponse schema) — echoing the caller-supplied ``url`` would violate
    the URI format whenever it isn't one.
    """
    del url
    base = f"{config.base_url}"
    return {
        "type": "link",
        "version": "1.0",
        "title": "mastodon_mock",
        "author_name": "",
        "author_url": f"{base}/",
        "provider_name": "mastodon_mock",
        "provider_url": f"{base}/",
        "html": "",
        "width": 400,
        # The reconstructed OEmbedResponse schema types height as string|null.
        "height": None,
        "cache_age": 86400,
    }


# --- Annual reports ("Wrapstodon") -----------------------------------------


@router.get("/api/v1/annual_reports")
def annual_reports() -> dict[str, Any]:
    """No annual reports are ever generated by the mock."""
    return {"annual_reports": []}


@router.get("/api/v1/annual_reports/{year}")
def annual_report(year: str) -> dict[str, Any]:
    """No annual reports are ever generated by the mock."""
    del year
    raise HTTPException(status_code=404, detail="Record not found")


@router.get("/api/v1/annual_reports/{year}/state")
def annual_report_state(year: str) -> dict[str, Any]:
    """Annual reports are never eligible in the mock."""
    del year
    return {"state": "ineligible"}


@router.post("/api/v1/annual_reports/{year}/generate", status_code=200)
def annual_report_generate(year: str, account: RequiredAccount) -> dict[str, Any]:
    """Accept the generation request; no report is ever produced."""
    del year, account
    return {}


@router.post("/api/v1/annual_reports/{year}/read", status_code=200)
def annual_report_read(year: str, account: RequiredAccount) -> dict[str, Any]:
    """Mark an annual report as read; no-op since none exist."""
    del year, account
    return {}


# --- Async refreshes ---------------------------------------------------


@router.get("/api/v1_alpha/async_refreshes/{refresh_id}")
def async_refresh_status(refresh_id: str) -> dict[str, Any]:
    """The mock never runs background refresh jobs; everything is already complete."""
    return {"async_refresh": {"id": refresh_id, "status": "finished"}}
